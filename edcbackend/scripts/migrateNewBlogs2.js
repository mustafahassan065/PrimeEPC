async function addNewBlogs() {
  try {
    console.log('🔄 Starting blog migration...')
    await Blog.findOne({ where: {} })
    console.log('✅ Database connection working')

    let added = 0
    let skipped = 0

    for (const blog of newBlogs) {
      const existing = await Blog.findOne({ where: { slug: blog.slug } })
      if (existing) {
        console.log(`⏭️  Already exists: "${blog.title}"`)
        skipped++
        continue
      }
      const now = new Date()
      await Blog.create({
        title:            blog.title,
        slug:             blog.slug,
        meta_title:       blog.metaTitle,
        meta_description: blog.metaDescription,
        keywords:         JSON.stringify(blog.keywords || []),
        content:          blog.content,
        featured_image:   blog.featuredImage,
        excerpt:          blog.excerpt || '',
        status:           blog.status || 'published',
        author:           blog.author || 'Prime EPC',
        created_at:       now,
        updated_at:       now,
      })
      console.log(`✅ Added: "${blog.title}"`)
      added++
    }

    console.log(`\n🎉 Done — Added: ${added}, Skipped: ${skipped}`)
    const total = await Blog.count()
    console.log(`📋 Total blogs in DB: ${total}`)
    process.exit(0)
  } catch (error) {
    console.error('❌ Migration failed:', error)
    process.exit(1)
  }
}

